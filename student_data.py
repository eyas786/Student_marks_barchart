import numpy as np
import matplotlib.pyplot as plt
students=["ali","sara","ahmad","bilal","ayesha"]
marks=np.array([[70,85,40,55,75],[80,95,50,65,85]])
print("marks of students",marks)
print("array shape =",marks.shape)
print("array size =",marks.size)
print("dimensions =",marks.ndim)
print("data type =",marks.dtype)
print("sara test 2 score is :",marks[1,1])
print("score of first 3 student is :",marks[:3,:3])
avg=np.mean(marks,axis=0)
print("student average is:",avg)
print("test average is:",np.mean(marks,axis=1))
print("the highiest score is :",np.max(marks))
print("the lowest score is :",np.min(marks))
print("the student whose average is greater than 60:",np.sum(avg>=60))
print("orignal marks = ",marks)
print("bonus marks is = ",marks+5)
plt.bar(students,avg)
plt.title(" ITPS student average Marks")
plt.xlabel("Students")
plt.ylabel("Average Marks")
plt.savefig("student_marks_chart.png")
plt.show()